"""Tables of the gelu_silu kernel (fpga/kernels/gelu_silu): one generator for the HLS header and the torch emulation.

Both activations are x * h(x) with a sigmoid-like gate h in [0, 1] and h(-t) = 1 - h(t):
    GELU (tanh, SigLIP gelu_pytorch_tanh)  h(x) = 0.5 (1 + tanh(sqrt(2/pi) (x + 0.044715 x^3)))
    SiLU (LM / expert MLP gate)            h(x) = sigmoid(x)
The kernel tabulates g(t) = 1 - h(t) for t = |x| in [0, R) (GELU R = 8, SiLU R = 16; g = 0 beyond) on NSEG uniform
segments, each a straight line evaluated at 12-bit sub-segment resolution:
    T   = floor(|x| * 2^(NSB + 12 - log2 R))           (NSB + 12 bits: index NSB bits, fraction f 12 bits)
    g21 = V[idx] - ((D[idx] * f + 2048) >> 12)          (Q0.21, clamped at 0)
V (21 bits) and D (15 bits) are packed in one 36-bit ROM word (V << 15 | D): one BRAM36 holds 1024 words, so both
modes at NSEG = 512 fit one BRAM36, which is dual-ported and serves two lanes. D is the chord drop over the segment;
V is the midrange (minimax) offset over the 4096 discrete positions, each evaluated at the centre of the |x| interval
that floor() maps to it, so the truncation of T is unbiased.

    python gs_tables.py            # writes gelu_silu_tables.h next to this file (NSB 9 and 10)
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

FB = 12  # fraction bits inside a segment
VB, DB = 21, 15  # V and D widths (V Q0.21, D in Q0.21 units)
MODES = ("gelu", "silu")
RANGE_BITS = {"gelu": 3, "silu": 4}  # R = 8, 16


def g_exact(mode: str, t: np.ndarray) -> np.ndarray:
    """g(t) = 1 - h(t) in float64, t >= 0."""
    if mode == "gelu":
        return 0.5 * (1.0 - np.tanh(math.sqrt(2.0 / math.pi) * (t + 0.044715 * t**3)))
    return 1.0 / (1.0 + np.exp(t))


def build(mode: str, nsb: int) -> np.ndarray:
    """(NSEG,) uint64 packed words V << 15 | D for one mode."""
    nseg = 1 << nsb
    rb = RANGE_BITS[mode]
    delta = 2.0**rb / nseg
    f = np.arange(1 << FB, dtype=np.int64)
    out = np.zeros(nseg, dtype=np.uint64)
    for i in range(nseg):
        a = i * delta
        D = int(round((g_exact(mode, np.array([a]))[0] - g_exact(mode, np.array([a + delta]))[0]) * 2.0**VB))
        assert 0 <= D < (1 << DB), (mode, i, D)
        tmid = a + (f + 0.5) * delta / (1 << FB)
        corr = (D * f + (1 << (FB - 1))) >> FB  # what the hardware subtracts
        want = g_exact(mode, tmid) * 2.0**VB + corr  # V that would make each position exact
        V = int(round(0.5 * (want.max() + want.min())))
        assert 0 <= V < (1 << VB), (mode, i, V)
        out[i] = (V << DB) | D
    return out


def table(nsb: int) -> np.ndarray:
    """(2 * NSEG,) packed words: GELU segments then SiLU segments (ROM address = mode * NSEG + idx)."""
    return np.concatenate([build(m, nsb) for m in MODES])


_CACHE: dict[int, np.ndarray] = {}


def cached_table(nsb: int) -> np.ndarray:
    if nsb not in _CACHE:
        _CACHE[nsb] = table(nsb)
    return _CACHE[nsb]


def write_header(path: Path, nsbs=(9, 10)) -> None:
    lines = [
        "// Generated by gs_tables.py (fpga/kernels/gelu_silu). Do not edit.",
        "// ROM word = V << 15 | D; address = mode * NSEG + idx (mode 0 GELU [0, 8), mode 1 SiLU [0, 16)).",
        "#pragma once",
    ]
    for nsb in nsbs:
        t = cached_table(nsb)
        body = ",".join(f"{int(v)}ULL" for v in t)
        lines.append(f"#define GS_TAB_INIT_{nsb} {{{body}}}")
    path.write_text("\n".join(lines) + "\n")


def report(nsb: int) -> None:
    """Max |g_hw - g| over a dense grid of FP32 |x| (float64 model of the table path, before the Q0.18 rounding)."""
    t = cached_table(nsb)
    nseg = 1 << nsb
    for mi, mode in enumerate(MODES):
        rb = RANGE_BITS[mode]
        x = np.linspace(0, 2.0**rb * 1.02, 2_000_001)
        T = np.floor(x * 2.0 ** (nsb + FB - rb)).astype(np.int64)
        sat = T >= (nseg << FB)
        idx = np.minimum(T >> FB, nseg - 1)
        fr = T & ((1 << FB) - 1)
        w = t[mi * nseg + idx].astype(np.int64)
        V, D = w >> DB, w & ((1 << DB) - 1)
        g21 = np.maximum(V - ((D * fr + (1 << (FB - 1))) >> FB), 0)
        g21 = np.where(sat, 0, g21)
        err = np.abs(g21 / 2.0**VB - g_exact(mode, x))
        print(f"NSB {nsb} {mode}: max |g_table - g| = {err.max():.3e}, max |x| * err = {(err * x).max():.3e}")


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    write_header(here / "gelu_silu_tables.h")
    for nsb in (9, 10):
        report(nsb)
    print("wrote", here / "gelu_silu_tables.h")
