"""Writes nr_tables.h: the recip / rsqrt seed tables of nr_emul.py as FP32 bit patterns (one source of truth)."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import nr_emul  # noqa: E402


def fmt(name, arr):
    vals = ", ".join(f"0x{int(b):08X}u" for b in arr.view("uint32"))
    return f"#define {name} {{{vals}}}\n"


out = pathlib.Path(__file__).resolve().parent / "nr_tables.h"
out.write_text("// Generated by gen_tables.py from nr_emul.py. Do not edit.\n#pragma once\n"
               "// 1 / (1 + (i + 0.5) / 128), i = top 7 fraction bits of a\n"
               + fmt("NR_RECIP_SEED_INIT", nr_emul.RECIP_SEED)
               + "// 1 / sqrt((1 + (i + 0.5) / 64) * (p ? 2 : 1)), index p * 64 + top 6 fraction bits of v\n"
               + fmt("NR_RSQRT_SEED_INIT", nr_emul.RSQRT_SEED))
print("wrote", out)
